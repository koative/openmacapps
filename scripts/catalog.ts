import fs from 'node:fs';
import path from 'node:path';
import { site } from '../src/lib/site.ts';
import {
  categories,
  getApps,
  catalogDirectory,
  type CatalogApp,
} from '../src/lib/catalog.ts';
import { loadAlternatives, loadTopics } from '../src/lib/guides.ts';
import { categorySlug } from '../src/lib/collections.ts';

const START = '<!-- catalog:start -->';
const END = '<!-- catalog:end -->';
// One list per category keeps every file under GitHub's 500 KiB README limit.
const CATALOG = 'catalog';
const command = process.argv[2] ?? 'validate';

function escapeCell(value: string): string {
  return value
    .replaceAll('|', '\\|')
    .replaceAll('[', '\\[')
    .replaceAll(']', '\\]')
    .replaceAll('\n', ' ');
}
function appRow(app: CatalogApp): string {
  return `| [${escapeCell(app.name)}](${site.url}apps/${app.slug}/) · [Source](${app.repository}) | ${escapeCell(app.summary)} | [${app.license}](${app.licenseUrl})${app.sourceAvailability === 'source-available' ? ' · **Source available**' : ''}${app.maintenance === 'unmaintained' ? ' · **Unmaintained**' : ''} |`;
}
function categoryPage(category: string, entries: CatalogApp[]): string {
  return `# ${category}\n\n<!-- Generated by \`bun run sync\` from content/apps. Edit the app folders, not this file. -->\n\n${entries.length.toLocaleString('en-US')} Mac apps in ${category}, also on [openmacapps.com](${site.url}categories/${categorySlug(category)}/). Back to the [README](../README.md).\n\n| App | What it does | License |\n| --- | --- | --- |\n${entries.map(appRow).join('\n')}\n`;
}
/** Every generated Markdown file by path: the README's category index and one list per category. */
function generatedFiles(apps: CatalogApp[]): Map<string, string> {
  const files = new Map<string, string>();
  const rows: string[] = [];
  for (const category of categories) {
    const entries = apps.filter((app) => app.category === category);
    if (!entries.length) continue;
    const file = `${CATALOG}/${categorySlug(category)}.md`;
    files.set(file, categoryPage(category, entries));
    rows.push(
      `| [${category}](${file}) | ${entries.length.toLocaleString('en-US')} |`,
    );
  }
  const openSourceCount = apps.filter(
    (app) => app.sourceAvailability === 'open-source',
  ).length;
  const block = `${START}\n\n${apps.length.toLocaleString('en-US')} macOS apps: **${openSourceCount.toLocaleString('en-US')} open source** and **${apps.length - openSourceCount} source available**. Source-available apps have additional restrictions and are labeled separately. Each category's list is generated from [content/apps](content/apps); edit the app folders to contribute.\n\n| Category | Apps |\n| --- | ---: |\n${rows.join('\n')}\n\n${END}`;
  const readme = fs.readFileSync('README.md', 'utf8');
  const start = readme.indexOf(START);
  const end = readme.indexOf(END);
  if (
    start < 0 ||
    end < start ||
    readme.indexOf(START, start + START.length) >= 0 ||
    readme.indexOf(END, end + END.length) >= 0
  ) {
    throw new Error(
      'README.md needs exactly one ordered pair of catalog:start / catalog:end markers',
    );
  }
  files.set(
    'README.md',
    `${readme.slice(0, start)}${block}${readme.slice(end + END.length)}`,
  );
  return files;
}
/** Generated files that differ from what is on disk, plus leftover lists. */
function staleFiles(files: Map<string, string>): string[] {
  const leftovers = fs.existsSync(CATALOG)
    ? fs
        .readdirSync(CATALOG)
        .map((name) => `${CATALOG}/${name}`)
        .filter((file) => !files.has(file))
    : [];
  return [
    ...[...files]
      .filter(
        ([file, content]) =>
          !fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== content,
      )
      .map(([file]) => file),
    ...leftovers,
  ];
}
try {
  if (!['validate', 'sync', 'check'].includes(command))
    throw new Error(`Unknown command: ${command}`);
  const apps = getApps();
  if (!apps.length)
    throw new Error('The catalog must contain at least one app');
  const alternatives = loadAlternatives(apps);
  const topics = loadTopics(apps);
  if (command === 'sync') {
    const files = generatedFiles(apps);
    const output = path.resolve('public/catalog');
    fs.rmSync(output, { recursive: true, force: true });
    fs.mkdirSync(output, { recursive: true });
    for (const app of apps) {
      for (const notice of app.notices) {
        const target = path.join(output, app.slug, notice.path);
        fs.mkdirSync(path.dirname(target), { recursive: true });
        fs.copyFileSync(
          path.join(catalogDirectory, app.slug, notice.path),
          target,
        );
      }
      for (const asset of app.assets) {
        const target = path.join(output, app.slug, asset.path);
        fs.mkdirSync(path.dirname(target), { recursive: true });
        fs.copyFileSync(
          path.join(catalogDirectory, app.slug, asset.path),
          target,
        );
      }
    }
    fs.writeFileSync(
      'public/catalog.json',
      `${JSON.stringify(apps, null, 2)}\n`,
    );
    fs.rmSync(CATALOG, { recursive: true, force: true });
    fs.mkdirSync(CATALOG);
    for (const [file, content] of files) fs.writeFileSync(file, content);
  }
  if (command === 'check') {
    const stale = staleFiles(generatedFiles(apps));
    if (stale.length)
      throw new Error(
        `Generated catalog is stale (${stale.join(', ')}). Run bun run sync and commit README.md and catalog/.`,
      );
  }
  console.log(
    `${command}: ${apps.length} app records, ${alternatives.length} alternatives pages and ${topics.length} topic pages validated${command === 'sync' ? '; assets, JSON, README and catalog lists generated' : ''}.`,
  );
} catch (error) {
  console.error(error instanceof Error ? error.message : String(error));
  process.exitCode = 1;
}
